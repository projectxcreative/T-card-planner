#!/usr/bin/env node
/**
 * Turns a board export (Settings → Backup → Export a backup) into SQL that
 * loads it into the Supabase schema in supabase/migrations.
 *
 *   node scripts/board-to-sql.mjs t-card-planner-2026-11-25.json > import.sql
 *
 * Paste import.sql into the Supabase SQL editor, or run it with psql. It is
 * one transaction: it either loads everything or nothing.
 *
 * What changes on the way in:
 * - A card had a list of clients; now it has one owner. The first client on
 *   the card that still exists becomes the owner, falling back to its
 *   project's client. Any others are kept as staff-only tags.
 * - Nothing is shared with clients. Every card arrives with client_visible
 *   off, so the portal shows nothing until you choose what to share.
 * - Lanes become a lane name and a position on each card.
 * - Attachments arrive as rows only. The files themselves are still in KV and
 *   are copied separately; the storage path each one should land at is
 *   printed to stderr as a manifest.
 */
import { readFileSync } from 'node:fs';

const file = process.argv[2];
if (!file) {
  console.error('usage: node scripts/board-to-sql.mjs <board export .json>');
  process.exit(1);
}

const board = JSON.parse(readFileSync(file, 'utf8'));
for (const key of ['cards', 'lanes', 'projects', 'clients']) {
  if (!board[key] || typeof board[key] !== 'object') {
    console.error(`${file} doesn't look like a T-Card Planner export: no "${key}".`);
    process.exit(1);
  }
}

/* ---------- SQL literals ---------- */

function q(value) {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : 'null';
  return `'${String(value).replace(/'/g, "''")}'`;
}

const HEX = /^#[0-9a-fA-F]{6}$/;
const colour = (c, fallback = '#64748b') => (typeof c === 'string' && HEX.test(c) ? c : fallback);
const DAY = /^\d{4}-\d{2}-\d{2}$/;
const MONTH = /^\d{4}-\d{2}$/;
const STATUSES = new Set(['todo', 'doing', 'blocked', 'done']);
const STAGES = new Set(['enquiry', 'quoted', 'won', 'active', 'delivered', 'invoiced', 'paid', 'lost']);
const BUCKETS = new Set(['todo', 'due', 'sent', 'paid']);
const num = (n, fallback = 0) => (typeof n === 'number' && Number.isFinite(n) ? n : fallback);
const str = (s, fallback = '') => (typeof s === 'string' ? s : fallback);
const ts = (s) => (typeof s === 'string' && s && !Number.isNaN(Date.parse(s)) ? s : null);
const safeName = (name) => str(name, 'file').replace(/[/\\]/g, '_').slice(0, 120) || 'file';

const out = [];
const manifest = [];
const insert = (table, row) => {
  const cols = Object.keys(row);
  out.push(`insert into public.${table} (${cols.join(', ')}) values (${cols.map((c) => row[c]).join(', ')});`);
};

out.push('-- Generated by scripts/board-to-sql.mjs from ' + file.replace(/\n/g, ' '));
out.push('begin;');

/* ---------- lookups ---------- */

const categoryOrder = Array.isArray(board.categoryOrder) ? board.categoryOrder : Object.keys(board.categories || {});
for (const [id, cat] of Object.entries(board.categories || {})) {
  insert('categories', {
    id: q(id), label: q(str(cat?.label)), colour: q(colour(cat?.colour)),
    sort_order: q(Math.max(0, categoryOrder.indexOf(id))),
  });
}
const updateOrder = Array.isArray(board.updateCategoryOrder) ? board.updateCategoryOrder : Object.keys(board.updateCategories || {});
for (const [id, cat] of Object.entries(board.updateCategories || {})) {
  insert('update_categories', {
    id: q(id), label: q(str(cat?.label)), colour: q(colour(cat?.colour)),
    sort_order: q(Math.max(0, updateOrder.indexOf(id))),
  });
}

/* ---------- clients ---------- */

const clientOrder = Array.isArray(board.clientOrder) ? board.clientOrder : Object.keys(board.clients);
for (const [id, client] of Object.entries(board.clients)) {
  insert('clients', {
    id: q(id), name: q(str(client?.name, 'Client').slice(0, 80) || 'Client'),
    colour: q(colour(client?.colour)), sort_order: q(Math.max(0, clientOrder.indexOf(id))),
  });
}
const clientExists = (id) => typeof id === 'string' && Object.hasOwn(board.clients, id);

/* ---------- projects ---------- */

const storagePath = (owner, id, name) => `${owner || 'internal'}/${id}/${safeName(name)}`;

function attachments(list, parent, owner) {
  for (const a of Array.isArray(list) ? list : []) {
    if (!a?.id) continue;
    const path = storagePath(owner, a.id, a.name);
    insert('attachments', {
      id: q(a.id), card_id: q(parent.card ?? null), project_id: q(parent.project ?? null),
      name: q(str(a.name, 'file')), mime_type: q(str(a.type, 'application/octet-stream')),
      size: q(num(a.size)), storage_path: q(path), client_visible: 'false',
      created_at: ts(a.createdAt) ? q(a.createdAt) : 'now()',
    });
    manifest.push({ id: a.id, storagePath: path, type: str(a.type) });
  }
}

for (const [id, p] of Object.entries(board.projects)) {
  const owner = clientExists(p?.clientId) ? p.clientId : null;
  insert('projects', {
    id: q(id), title: q(str(p?.title)), description: q(str(p?.description)),
    value: q(num(p?.value)), budget_hours: q(num(p?.budgetHours)),
    stage: q(STAGES.has(p?.stage) ? p.stage : 'enquiry'), client_id: q(owner),
    invoice_month: q(MONTH.test(str(p?.invoiceMonth)) ? p.invoiceMonth : null),
    category_id: q(p?.colour ?? null), archived: q(Boolean(p?.archived)),
    created_at: ts(p?.createdAt) ? q(p.createdAt) : 'now()',
    updated_at: ts(p?.updatedAt) ? q(p.updatedAt) : 'now()',
  });
  (Array.isArray(p?.milestones) ? p.milestones : []).forEach((m, i) => {
    insert('project_milestones', {
      id: m?.id ? q(m.id) : 'public.new_id()', project_id: q(id), label: q(str(m.label)), amount: q(num(m.amount)),
      invoice_month: q(MONTH.test(str(m.invoiceMonth)) ? m.invoiceMonth : null),
      status: q(BUCKETS.has(m.status) ? m.status : 'todo'), sort_order: q(i),
    });
  });
  (Array.isArray(p?.expenses) ? p.expenses : []).forEach((e, i) => {
    insert('expenses', {
      id: e?.id ? q(e.id) : 'public.new_id()', project_id: q(id), label: q(str(e.label)), amount: q(num(e.amount)),
      chargeable: q(Boolean(e.chargeable)), sort_order: q(i),
    });
  });
  attachments(p?.attachments, { project: id }, owner);
}

/* ---------- cards ---------- */

const placement = new Map();
for (const [lane, ids] of Object.entries(board.lanes)) {
  if (lane !== 'backlog' && !DAY.test(lane)) continue;
  (Array.isArray(ids) ? ids : []).forEach((cardId, i) => {
    if (!placement.has(cardId)) placement.set(cardId, { lane, position: i });
  });
}

let unplaced = 0;
for (const [id, c] of Object.entries(board.cards)) {
  const tags = (Array.isArray(c?.clients) ? c.clients : []).filter(clientExists);
  const projectClient = board.projects[c?.projectId]?.clientId;
  const owner = tags[0] ?? (clientExists(projectClient) ? projectClient : null);
  let place = placement.get(id);
  if (!place) {
    unplaced += 1;
    place = { lane: 'backlog', position: 100000 + unplaced };
  }
  insert('cards', {
    id: q(id), title: q(str(c?.title)), description: q(str(c?.description)),
    category_id: q(c?.colour ?? null), status: q(STATUSES.has(c?.status) ? c.status : 'todo'),
    estimate: q(num(c?.estimate)),
    start_minute: q(Number.isInteger(c?.start) && c.start >= 0 && c.start < 1440 ? c.start : null),
    due_date: q(DAY.test(str(c?.dueDate)) ? c.dueDate : null),
    lane: q(place.lane), position: q(place.position),
    project_id: q(c?.projectId && board.projects[c.projectId] ? c.projectId : null),
    client_id: q(owner), client_visible: 'false',
    publish: q(Boolean(c?.publish)), event_id: q(c?.eventId ?? null),
    completed_at: q(ts(c?.completedAt)),
    created_at: ts(c?.createdAt) ? q(c.createdAt) : 'now()',
    updated_at: ts(c?.updatedAt) ? q(c.updatedAt) : 'now()',
  });
  for (const tag of tags) {
    if (tag !== owner) insert('card_tags', { card_id: q(id), client_id: q(tag) });
  }
  for (const u of Array.isArray(c?.updates) ? c.updates : []) {
    if (!u?.id) continue;
    const day = DAY.test(str(u.date)) ? u.date : str(u.createdAt).slice(0, 10);
    insert('card_updates', {
      id: q(u.id), card_id: q(id), category_id: q(u.categoryId ?? null),
      minutes: q(Math.max(0, Math.round(num(u.minutes)))), note: q(str(u.note)),
      date: DAY.test(day) ? q(day) : 'current_date',
      created_at: ts(u.createdAt) ? q(u.createdAt) : 'now()',
    });
  }
  attachments(c?.attachments, { card: id }, owner);
}

for (const eventId of Array.isArray(board.orphanedEvents) ? board.orphanedEvents : []) {
  if (typeof eventId === 'string' && eventId) {
    out.push(`insert into public.orphaned_events (event_id) values (${q(eventId)}) on conflict do nothing;`);
  }
}

out.push('commit;');
process.stdout.write(out.join('\n') + '\n');

const counts = {
  clients: Object.keys(board.clients).length,
  projects: Object.keys(board.projects).length,
  cards: Object.keys(board.cards).length,
  attachments: manifest.length,
  cardsNotInAnyLane: unplaced,
};
console.error(`Converted ${JSON.stringify(counts)}`);
console.error('Attachment manifest (KV file id -> storage path):');
console.error(JSON.stringify(manifest, null, 2));
